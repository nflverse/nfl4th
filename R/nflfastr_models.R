# ---- from nflfastR helper_add_ot_wp.R
ot_s_grid <- seq(-14, 14, by = 2) # spread grid (posteam perspective)

# ---- from nflfastR helper_add_ot_wp.R
ot_step <- 5 # seconds per time node

# ---- from nflfastR helper_add_ot_wp.R
ot_n <- 180L # nodes: 0 ... 900 seconds

# ---- from nflfastR helper_add_ot_wp.R
# The dynamic program is solved on the grid above but only every 2nd time node
# is stored (values are smooth in time and are interpolated when used) to keep
# R/sysdata.rda small. Thinning the spread grid costs too much accuracy.
ot_s_store <- ot_s_grid

# ---- from nflfastR helper_add_ot_wp.R
ot_t_stride <- 2L

# ---- from nflfastR helper_add_ot_wp.R
ot_d_set <- c(0, -3, -6, -7, -8) # score differentials of the receiving team

# ---- from nflfastR helper_add_ot_wp.R
ot_2pt_prob <- 0.4735 # same value as the PAT fix in add_wp_variables()

# ---- from nflfastR helper_add_ot_wp.R
ot_outcomes <- c("TD", "FG", "SAF", "OPPTD", "STOP")

# ---- from nflfastR helper_add_ot_wp.R
# the drive model has a sixth class, PUNT, that is part of STOP for durations.
# It is only used to model teams that must score (see ot_apply_must_score())
ot_go_avg <- 0.45 # average 4th down conversion rate when going for it

# ---- from nflfastR helper_add_ot_wp.R
# first season of kickoff regimes 2 to 5 (regime 1 is everything before). Where
# drives start changed with the kickoff rules. data-raw/ot_wp_model.R builds the
# training windows from the same seasons.
ot_kick_first <- c(2011L, 2016L, 2024L, 2025L)

# ---- from nflfastR helper_add_ot_wp.R
# rule, period length and kickoff regime for each game
ot_rule_key <- function(season, season_type) {
  post <- season_type %in% "POST"
  rule <- case_when(
    post & season >= 2022 ~ "BOTH",
    !post & season >= 2025 ~ "BOTH",
    post & season >= 2010 ~ "MSD",
    !post & season >= 2012 ~ "MSD",
    TRUE ~ "SD"
  )
  len <- if_else(!post & season >= 2017, 600L, 900L)
  # kickoff regime determines where drives start
  kick <- findInterval(season, ot_kick_first) + 1L
  paste(rule, len, kick, sep = "|")
}

# ---- from nflfastR helper_add_ot_wp.R
# season_type is not available when win probability is added, so derive it
# from the week in the game id
ot_season_type <- function(game_id, season) {
  wk <- suppressWarnings(as.integer(substr(game_id, 6, 7)))
  if_else(wk > if_else(season >= 2021, 18L, 17L), "POST", "REG")
}

# ---- from nflfastR helper_add_ot_wp.R
# Score differentials the rules can produce (receiving team, start of a
# possession) are exactly ot_d_set. Anything else, such as a lead or a deficit
# of 1 or 2 points, can't occur in the supported rules and snaps to the nearest
# value (a lead of 3 or 7 therefore counts as tied).
ot_map_d <- function(x) {
  vapply(x, function(z) which.min(abs(z - ot_d_set) - 1e-6 * ot_d_set), 1L)
}

# ---- from nflfastR helper_add_ot_wp.R
# 1 ahead, 0 behind, 0.5 tied (or unknown)
ot_end_value <- function(d) {
  v <- rep(0.5, length(d))
  v[which(d > 0)] <- 1
  v[which(d < 0)] <- 0
  v
}

# ---- from nflfastR helper_add_ot_wp.R
# Possible results of a completed possession for the team that had the ball
# (R). Returns a list of components. Each has a weight w and either a terminal
# value (for R) or the state in which the opponent starts a possession.
ot_trans <- function(rule, p, d, kind) {
  term <- function(v, w = 1) list(w = w, val = v)
  cont <- function(ty, p2, d2, w = 1) {
    list(w = w, val = NA_real_, ty = ty, p = p2, di = ot_map_d(d2))
  }
  if (kind == "STOP") {
    if (rule == "SD") {
      return(list(cont(2L, 3, 0)))
    }
    if (p == 2 && d < 0) {
      return(list(term(0)))
    }
    return(list(cont(2L, min(p + 1, 3), -d)))
  }
  pts <- if (kind == "TD") 7 else 3
  d2 <- d + pts
  if (rule == "SD") {
    return(list(term(1)))
  }
  if (p == 1) {
    if (rule == "MSD" && pts == 7) {
      return(list(term(1)))
    }
    return(list(cont(1L, 2, -d2)))
  }
  if (p == 2) {
    if (d2 > 0) {
      return(list(term(1)))
    }
    if (d2 == 0) {
      return(list(cont(1L, 3, 0)))
    }
    if (d2 == -1) {
      # TD but still trailing by one after a team scored TD + 2: go for two
      return(list(
        cont(1L, 3, 0, w = ot_2pt_prob),
        term(0, w = 1 - ot_2pt_prob)
      ))
    }
    return(list(term(0)))
  }
  list(term(1))
}

# ---- from nflfastR helper_add_ot_wp.R
# interpolate a stored [spread x time] matrix. `tn` is time in 5 second nodes
ot_q_interp <- function(Qm, s, tn) {
  S <- length(ot_s_store)
  sc <- pmin(pmax(s, ot_s_store[1]), ot_s_store[S])
  pos <- (sc - ot_s_store[1]) / (ot_s_store[2] - ot_s_store[1]) + 1
  i0 <- min(floor(pos), S - 1L)
  fs <- pos - i0
  row <- Qm[i0, ] * (1 - fs) + Qm[i0 + 1L, ] * fs
  nt <- ncol(Qm)
  tp <- pmin(pmax(tn / ot_t_stride, 0), nt - 1) + 1
  k0 <- pmin(floor(tp), nt - 1L)
  ft <- tp - k0
  row[k0] * (1 - ft) + row[k0 + 1L] * ft
}

# ---- from nflfastR helper_add_ot_wp.R
# Offenses hurry when the clock is short, so a possession takes a fraction of
# its normal time. A normal play takes about 38 seconds of game clock. The
# ratios above two minutes come from regulation two minute drills (tied or
# trailing by up to 8, drives that scored). Below that the drives we can
# observe are only the ones that finished in time, which makes the ratio look
# smaller than it is, so the curve levels off at a floor of about 6.5 seconds
# per play (snap to whistle plus spikes and timeouts) instead of following the
# data down.
#
# The chance that a possession finishes before the clock runs out must never
# fall when there is more time. A possession needs `ratio * normal time`, so
# that requires ratio / secs to never increase. All knots are chosen so that
# this holds (it is checked in tests/testthat/test-ot_wp.R). Without it a team
# with 30 seconds left looked more likely to score than the same team with 60
# seconds left. Note that win probability itself is not monotone in the clock:
# more time also gives the other team a chance to answer.
ot_tempo <- function(secs) {
  stats::approx(
    x = c(0, 45, 75, 105, 150, 210, 270, 330),
    y = c(0.17, 0.17, 0.28, 0.39, 0.48, 0.65, 0.82, 1),
    xout = secs,
    rule = 2
  )$y
}

# ---- from nflfastR helper_add_ot_wp.R
ot_cache <- new.env(parent = emptyenv())

# ---- from nflfastR helper_add_ot_wp.R
ot_load_boosters <- function() {
  if (is.null(ot_cache$out)) {
    tryCatch(
      {
        ot_cache$out <- xgboost::xgb.load.raw(ot_wp_models$out_raw)
        ot_cache$dur <- xgboost::xgb.load.raw(ot_wp_models$dur_raw)
      },
      error = function(e) {
        cli::cli_abort(
          c(
            "Can't load the overtime win probability models.",
            "i" = "They were saved with xgboost {.val {ot_wp_models$xgboost_version}} and you have {.val {as.character(utils::packageVersion('xgboost'))}}.",
            "x" = conditionMessage(e)
          )
        )
      }
    )
  }
  ot_cache
}

# ---- from nflfastR helper_add_ot_wp.R
ot_predict_matrix <- function(model, x) {
  p <- stats::predict(model, x)
  if (is.vector(p)) {
    p <- matrix(p, nrow = nrow(x), byrow = TRUE)
  }
  p
}

# ---- from nflfastR helper_add_ot_wp.R
# 4th down conversion probability for a team that has to go for it
ot_go_prob <- function(ydstogo) {
  stats::plogis(0.75 - 0.17 * pmin(ydstogo, 30))
}

# ---- from nflfastR helper_add_ot_wp.R
# The drive model learned from teams that punt on 4th down. A team that is
# behind on its last possession cannot. Instead of punting, it converts with
# probability `c` and then has a fresh drive with scoring probabilities `r`.
# P has columns TD, FG, SAF, OPPTD, STOP (STOP includes punts), pun is the
# probability of a punt and c, r1, r2 the conversion probability and the
# TD / FG probability of the continued drive
ot_apply_must_score <- function(P, pun, c, r1, r2) {
  gain1 <- pun * c * r1
  gain2 <- pun * c * r2
  P[, 1] <- P[, 1] + gain1
  P[, 2] <- P[, 2] + gain2
  P[, 5] <- P[, 5] - gain1 - gain2
  P
}

# ---- from nflfastR helper_add_ot_wp.R
# collapse the 6 class model output to the 5 outcomes used in the recursion
ot_collapse_preds <- function(p6) {
  list(
    P = cbind(p6[, 1:4, drop = FALSE], p6[, 5] + p6[, 6]),
    pun = p6[, 6]
  )
}

# ---- from nflfastR helper_add_ot_wp.R
# drive outcome probabilities and expected remaining drive time (per outcome).
# `cont_feat` are the states of a drive that continues after a conversion
ot_drive_preds <- function(feat, cont_feat) {
  b <- ot_load_boosters()
  n <- nrow(feat)
  # one call per model (each row is predicted on its own): the outcome model for
  # both feature sets, the duration model for every outcome
  p6 <- ot_predict_matrix(b$out, rbind(feat, cont_feat))
  cp <- ot_collapse_preds(p6[seq_len(n), , drop = FALSE])
  r <- ot_collapse_preds(p6[n + seq_len(n), , drop = FALSE])$P
  K <- length(ot_outcomes)
  oh <- diag(K)[rep(seq_len(K), each = n), , drop = FALSE]
  dur <- stats::predict(
    b$dur,
    cbind(feat[rep(seq_len(n), K), , drop = FALSE], oh)
  )
  # the duration model predicts in units of `dur_unit` seconds
  mu <- matrix(pmax(dur * ot_wp_models$dur_unit - 5, 3), nrow = n)
  list(P = cp$P, pun = cp$pun, mu = mu, r1 = r[, 1], r2 = r[, 2])
}

# ---- from nflfastR helper_add_ot_wp.R
# ot_q_interp() for many rows at once: spread s[r] and the times in row r of
# the matrix tn. Returns a matrix like tn.
ot_q_interp_rows <- function(Qm, s, tn) {
  S <- length(ot_s_store)
  sc <- pmin(pmax(s, ot_s_store[1]), ot_s_store[S])
  pos <- (sc - ot_s_store[1]) / (ot_s_store[2] - ot_s_store[1]) + 1
  i0 <- pmin(floor(pos), S - 1L)
  fs <- pos - i0
  rows <- Qm[i0, , drop = FALSE] * (1 - fs) + Qm[i0 + 1L, , drop = FALSE] * fs
  nt <- ncol(Qm)
  tp <- pmin(pmax(tn / ot_t_stride, 0), nt - 1) + 1
  k0 <- pmin(floor(tp), nt - 1L)
  ft <- tp - k0
  r <- c(row(tn))
  k0 <- c(k0)
  matrix(
    rows[cbind(r, k0)] * (1 - c(ft)) + rows[cbind(r, k0 + 1L)] * c(ft),
    nrow(tn)
  )
}

# ---- from nflfastR helper_add_ot_wp.R
# value to the team with the ball in the middle of a possession, for rows that
# share the rules, possession number and score (dp, rule, p, di) and differ in
# clock (secs), spread (s), outcome probabilities (P, one row each) and drive
# times (mu). Row by row this is the same arithmetic as valuing each row on its
# own: sums run over the nodes in the same order (rowSums() and sum() both
# accumulate in long double), with nodes past the clock adding 0.
ot_rows_scrimmage <- function(dp, rule, p, di, secs, s, P, mu) {
  shape <- ot_wp_models$shape
  d <- ot_d_set[di]
  m <- length(secs)
  j <- matrix(seq_len(ot_n), m, ot_n, byrow = TRUE)
  # the last snap of a possession has to happen before the clock expires, so a
  # possession can still finish up to one play after time has run out
  tt <- secs / ot_step - j
  tleft <- pmax(tt, 0)
  past <- !(tt > -1)
  up <- matrix((seq_len(ot_n) + 0.5) * ot_step, m, ot_n, byrow = TRUE)
  tempo <- ot_tempo(secs)
  val <- 0
  for (o in c(1L, 2L, 5L)) {
    kind <- ot_outcomes[o]
    # ot_pmf() for each row
    scale <- pmax(mu[, o] * tempo, 3) / shape[[kind]]
    cdf <- matrix(stats::pgamma(up, shape[[kind]], scale = scale), m)
    pm <- cdf - cbind(0, cdf[, -ot_n, drop = FALSE])
    pm_in <- pm
    pm_in[past] <- 0
    pm_sum <- rowSums(pm_in)
    comps <- ot_trans(rule, p, d, kind)
    v <- 0
    for (cp in comps) {
      if (is.na(cp$val)) {
        qv <- ot_q_interp_rows(dp$Q[cp$ty, cp$p, cp$di, , ], -s, tleft)
        cont <- pm * (1 - qv)
        cont[past] <- 0
        v <- v + cp$w * rowSums(cont)
      } else {
        v <- v + cp$w * cp$val * pm_sum
      }
    }
    val <- val + P[, o] * (v + (1 - pm_sum) * ot_end_value(d))
  }
  # SAF / OPPTD: the other team scored and wins
  val
}

# ---- from nflfastR helper_add_ot_wp.R
# value to the scoring team after the point(s) after touchdown are resolved
ot_row_post_score <- function(dp, rule, p, d2, secs, s) {
  if (d2 > 0) {
    if (p == 1 && rule == "BOTH") {
      return(
        1 -
          ot_q_interp(
            dp$Q[1, 2, ot_map_d(-d2), , ],
            -s,
            secs / ot_step
          )
      )
    }
    return(1)
  }
  if (d2 == 0 && p == 2) {
    return(1 - ot_q_interp(dp$Q[1, 3, 1, , ], -s, secs / ot_step))
  }
  if (d2 < 0) {
    return(0)
  }
  0.5
}

# ---- from nflfastR helper_add_ot_wp.R
# possession number of each row in overtime (NA outside of overtime)
# A new possession starts when the drive changes. The drive id can also stay the
# same when the ball changes hands, e.g. a fumble or interception inside a
# drive that is recovered right away, so a change of posteam (ignoring kickoff
# rows, which carry the kicking team) starts a new possession as well.
ot_possession_number <- function(pbp) {
  dr <- if ("fixed_drive" %in% names(pbp)) pbp$fixed_drive else pbp$drive
  ot <- pbp$qtr > 4
  is_kick <- if ("kickoff_attempt" %in% names(pbp)) {
    pbp$kickoff_attempt %in% 1
  } else {
    rep(FALSE, nrow(pbp))
  }
  # rows without a team (timeouts, end of period) don't change possession
  team <- match(pbp$posteam, unique(stats::na.omit(pbp$posteam)))
  team[!ot | is_kick] <- NA
  dr[!ot] <- NA
  # counts changes of posteam within a drive
  segment <- stats::ave(
    team,
    pbp$game_id,
    dr,
    FUN = function(x) {
      k <- !is.na(x)
      out <- numeric(length(x))
      if (any(k)) {
        out[k] <- cumsum(c(0, diff(x[k]) != 0))
        last <- cummax(seq_along(x) * k)
        out <- ifelse(last > 0, out[pmax(last, 1)], 0)
      }
      out
    }
  )
  id <- dr + segment / 1000
  out <- stats::ave(
    id,
    pbp$game_id,
    FUN = \(x) match(x, sort(unique(x[!is.na(x)])))
  )
  as.numeric(out)
}

# ---- from nflfastR helper_add_ot_wp.R
# Overtime win probability of the team with the ball.
# `st` has one row per state to value. Required columns: season, season_type,
# kind ("scrimmage", "kickoff", "pat", "twopt"), yardline_100, down, ydstogo,
# secs (seconds left in the period), d (score differential of the team with the
# ball), spread (spread of the team with the ball, only if use_spread), phase
# (possession number), p_make (PAT make prob). Optional: p_fg (probability that
# a field goal from here is good). If use_spread is FALSE the spread is ignored.
# A state that occurs more than once (the overtime kickoff valued for every
# kick at the end of regulation, say) is valued once.
ot_wp_states <- function(st, use_spread = TRUE) {
  n <- nrow(st)
  if (n == 0) {
    return(rep(NA_real_, n))
  }
  cols <- intersect(
    c(
      "season",
      "season_type",
      "kind",
      "yardline_100",
      "down",
      "ydstogo",
      "secs",
      "d",
      if (use_spread) "spread",
      "phase",
      "p_make",
      "p_fg"
    ),
    names(st)
  )
  id <- vctrs::vec_group_id(st[cols])
  u <- which(!duplicated(id))
  if (length(u) == n) {
    return(ot_wp_states_unique(st, use_spread))
  }
  ot_wp_states_unique(st[u, , drop = FALSE], use_spread)[id]
}

# ---- from nflfastR helper_add_ot_wp.R
ot_wp_states_unique <- function(st, use_spread) {
  n <- nrow(st)
  out <- rep(NA_real_, n)
  if (n == 0) {
    return(out)
  }
  key <- ot_rule_key(st$season, st$season_type)
  rule <- sub("\\|.*$", "", key)
  s <- if (use_spread) st$spread else rep(0, n)
  s[is.na(s)] <- 0
  s <- pmin(pmax(s, ot_s_grid[1]), ot_s_grid[length(ot_s_grid)])
  secs <- pmin(pmax(st$secs, 0), ot_n * ot_step)
  # Postseason games don't end when the period does. The next period starts and
  # play goes on, so there is no clock pressure and the end of the period has no
  # value of its own. Value those states as if there were lots of time left.
  secs[st$season_type %in% "POST"] <- ot_n * ot_step

  # sanitize the state
  di <- ot_map_d(st$d)
  p <- pmin(pmax(st$phase, 1), 3)
  p[rule == "SD"] <- 3
  di[rule == "SD"] <- 1L
  p[p == 1 & di != 1L] <- 2
  p[p == 3 & di != 1L] <- 2

  # A kickoff is valued as the receiving team's 1st and 10 at the typical start
  # after a kickoff (the spot the regulation model uses as well). Averaging the
  # drive model over all drive starts instead overvalued the receiving team
  # compared to its first snap.
  ko <- which(st$kind == "kickoff")
  if (length(ko) > 0) {
    st$kind[ko] <- "scrimmage"
    st$yardline_100[ko] <- wp_kickoff_start(st$season[ko])
    st$down[ko] <- 1
    st$ydstogo[ko] <- 10
    if ("p_fg" %in% names(st)) st$p_fg[ko] <- NA_real_
  }

  scrim <- which(st$kind == "scrimmage")
  if (length(scrim) > 0) {
    feat <- cbind(
      yardline_100 = pmin(pmax(st$yardline_100[scrim], 1), 99),
      down = st$down[scrim],
      ydstogo = pmin(st$ydstogo[scrim], 30),
      posteam_spread = s[scrim],
      season_c = pmin(pmax(st$season[scrim], 2006), 2026)
    )
    # state of a fresh drive after a conversion
    y_new <- pmax(
      feat[, "yardline_100"] -
        ifelse(feat[, "down"] == 4, feat[, "ydstogo"], 8),
      1
    )
    cont_feat <- feat
    cont_feat[, "yardline_100"] <- y_new
    cont_feat[, "down"] <- 1
    cont_feat[, "ydstogo"] <- pmin(y_new, 10)
    dpred <- ot_drive_preds(feat, cont_feat)
    # teams that have to score do not punt
    must <- p[scrim] == 2 & di[scrim] > 1L
    cc <- ifelse(feat[, "down"] == 4, ot_go_prob(feat[, "ydstogo"]), ot_go_avg)

    # 4th down with a short clock: nobody punts. In range the offense kicks a
    # field goal (if that helps), otherwise it goes for it.
    sc <- secs[scrim]
    dd <- di[scrim]
    pf <- if ("p_fg" %in% names(st)) {
      st$p_fg[scrim]
    } else {
      rep(NA_real_, length(scrim))
    }
    fourth <- feat[, "down"] == 4
    # a field goal helps when it wins or ties the game
    kick <- fourth &
      !is.na(pf) &
      dd %in% c(1L, 2L) &
      ((sc <= 45 & pf >= 0.1) | (p[scrim] == 2 & dd == 2L & pf >= 0.55))
    late_go <- fourth & sc <= 45 & !kick
    must <- (must | late_go) & !kick
    if (any(must)) {
      dpred$P[must, ] <- ot_apply_must_score(
        dpred$P[must, , drop = FALSE],
        dpred$pun[must],
        cc[must],
        dpred$r1[must],
        dpred$r2[must]
      )
    }
    if (any(kick)) {
      dpred$P[kick, ] <- cbind(0, pf[kick], 0, 0, 1 - pf[kick])
      dpred$mu[kick, ] <- 4
    }
  }

  has_dp <- !vapply(key, function(kk) is.null(ot_wp_dp[[kk]]), TRUE)
  valid <- has_dp & !is.na(secs) & !is.na(di)
  # scrimmage rows: in groups that share the rules, possession and score, in
  # chunks to bound the size of the [rows x time nodes] matrices
  sc <- which(valid & st$kind %in% "scrimmage")
  pf <- if ("p_fg" %in% names(st)) st$p_fg else rep(NA_real_, n)
  groups <- split(sc, list(key[sc], p[sc], di[sc]), drop = TRUE)
  for (g in groups) {
    for (i in split(g, ceiling(seq_along(g) / 2000))) {
      dp <- ot_wp_dp[[key[i[1]]]]
      ii <- match(i, scrim)
      out[i] <- ot_rows_scrimmage(
        dp,
        rule[i[1]],
        p[i[1]],
        di[i[1]],
        secs[i],
        s[i],
        dpred$P[ii, , drop = FALSE],
        dpred$mu[ii, , drop = FALSE]
      )
      # The offense can always kick a field goal instead. On 4th down that is
      # the usual choice, and with a play or two left it is the choice on any
      # down. Value that option with the rules (a miss gives the other team the
      # ball, or ends the game) and never go below it.
      kk <- i[which(!is.na(pf[i]) & (st$down[i] == 4 | secs[i] <= 12))]
      if (length(kk) > 0) {
        kick_val <- ot_rows_scrimmage(
          dp,
          rule[i[1]],
          p[i[1]],
          di[i[1]],
          secs[kk],
          s[kk],
          cbind(0, pf[kk], 0, 0, 1 - pf[kk]),
          matrix(4, length(kk), 5)
        )
        out[kk] <- pmax(out[kk], kick_val)
      }
    }
  }
  for (i in which(valid & !st$kind %in% "scrimmage")) {
    dp <- ot_wp_dp[[key[i]]]
    k <- st$kind[i]
    if (k == "pat") {
      pm <- st$p_make[i]
      out[i] <- pm *
        ot_row_post_score(dp, rule[i], p[i], st$d[i] + 1, secs[i], s[i]) +
        (1 - pm) *
          ot_row_post_score(dp, rule[i], p[i], st$d[i], secs[i], s[i])
    } else if (k == "twopt") {
      out[i] <- ot_2pt_prob *
        ot_row_post_score(dp, rule[i], p[i], st$d[i] + 2, secs[i], s[i]) +
        (1 - ot_2pt_prob) *
          ot_row_post_score(dp, rule[i], p[i], st$d[i], secs[i], s[i])
    }
  }
  out
}

# ---- from nflfastR helper_add_ot_wp.R
# Overtime rows (qtr > 4) of calculate_win_probability(). `pbp_data` is the
# user's data, `model_data` the same rows with `posteam_spread` added. Returns
# NULL without overtime rows, otherwise list(i, wp, vegas_wp) where `i` are the
# overtime rows.
calculate_ot_win_probability <- function(pbp_data, model_data, wp = TRUE) {
  if (!"qtr" %in% names(pbp_data)) {
    return(NULL)
  }
  i <- which(pbp_data$qtr > 4)
  if (length(i) == 0) {
    return(NULL)
  }
  if (!"season" %in% names(pbp_data)) {
    cli::cli_abort(
      "{.arg pbp_data} needs a {.field season} column to value overtime rows."
    )
  }
  x <- model_data[i, , drop = FALSE]
  season_type <- if ("season_type" %in% names(x)) {
    toupper(x$season_type)
  } else if ("game_id" %in% names(x)) {
    ot_season_type(x$game_id, x$season)
  } else {
    rep("REG", length(i))
  }
  phase <- if ("ot_possession" %in% names(x)) {
    x$ot_possession
  } else if (all(c("game_id", "drive") %in% names(pbp_data))) {
    ot_possession_number(pbp_data)[i]
  } else {
    rep(NA_real_, length(i))
  }
  # rows that are a snap (have a down and a team with the ball) but no
  # possession number can't be valued
  no_poss <- is.na(phase) & !is.na(x$down) & !is.na(x$posteam)
  if (any(no_poss)) {
    cli::cli_warn(c(
      "Can't value {sum(no_poss)} overtime row{?s} without a possession number.",
      "i" = "Add an {.field ot_possession} column (1, 2 or 3 for later possessions)."
    ))
  }
  # probability that a field goal from the current spot is good, for the option
  # to kick at the end of the period or on 4th down
  p_fg <- fg_make_prob(x[["season"]], x[["roof"]], x$yardline_100)
  st <- data.frame(
    season = x$season,
    season_type = season_type,
    kind = ifelse(is.na(x$down) | is.na(x$posteam), NA, "scrimmage"),
    yardline_100 = x$yardline_100,
    down = x$down,
    ydstogo = x$ydstogo,
    secs = x$game_seconds_remaining,
    d = x$score_differential,
    spread = x$posteam_spread,
    phase = phase,
    p_make = NA_real_,
    p_fg = p_fg,
    stringsAsFactors = FALSE
  )
  # rows without a state (no team, down, score or clock) get NA
  ok <- which(
    !is.na(st$kind) & !is.na(st$phase) & !is.na(st$d) & !is.na(st$secs)
  )
  out <- list(
    i = i,
    wp = rep(NA_real_, length(i)),
    vegas_wp = rep(NA_real_, length(i))
  )
  if (length(ok) > 0) {
    if (wp) {
      out$wp[ok] <- ot_wp_states(st[ok, , drop = FALSE], use_spread = FALSE)
    }
    out$vegas_wp[ok] <- ot_wp_states(st[ok, , drop = FALSE], use_spread = TRUE)
  }
  out
}

# ---- from nflfastR helper_add_vegas_wp.R
# where the receiving team's first snap typically is after a kickoff, by
# kickoff rule regime (the regimes of the overtime model, see ot_kick_first)
wp_kickoff_start <- function(season, st = wp_kick_start) {
  if (is.null(season)) {
    season <- NA_real_
  }
  regime <- findInterval(season, ot_kick_first) + 1L
  # without a season use the current rules
  regime[is.na(regime)] <- length(st)
  unname(st[regime])
}

# ---- from nflfastR helper_add_vegas_wp.R
# WP of the team with the ball at the start of overtime, before the coin toss:
# the average of receiving and kicking the overtime kickoff (overtime model)
wp_ot_start <- function(x) {
  n <- nrow(x)
  season <- if (is.null(x[["season"]])) rep(NA_real_, n) else x[["season"]]
  if (anyNA(season)) {
    season[is.na(season)] <- nflreadr::most_recent_season()
  }
  type <- if (is.null(x[["season_type"]])) {
    rep("REG", n)
  } else {
    coalesce(x[["season_type"]], "REG")
  }
  st <- data.frame(
    season = season,
    season_type = type,
    kind = "kickoff",
    yardline_100 = NA_real_,
    down = NA_real_,
    ydstogo = NA_real_,
    secs = ifelse(type == "POST" | season < 2017, 900, 600),
    d = 0,
    spread = x$posteam_spread,
    phase = 1,
    p_make = NA_real_
  )
  kick <- st
  kick$spread <- -x$posteam_spread
  w <- ot_wp_states(rbind(st, kick))
  0.5 * w[seq_len(n)] + 0.5 * (1 - w[n + seq_len(n)])
}

# ---- from nflfastR helper_fg_model.R
# Kicking has improved steadily since 1999. The eras are recency buckets, not
# rule changes. The last two are the ones nfl4th uses.
fg_era <- function(season) {
  findInterval(season, c(2004, 2009, 2014, 2023)) + 1L
}

# ---- from nflfastR helper_fg_model.R
# probability that a field goal from yardline_100 is good. A missing season is
# the most recent one, a missing roof is outdoors.
fg_make_prob <- function(season, roof, yardline_100) {
  n <- max(length(season), length(roof), length(yardline_100))
  season <- if (is.null(season)) rep(NA_real_, n) else rep_len(season, n)
  roof <- if (is.null(roof)) {
    rep(NA_character_, n)
  } else {
    rep_len(as.character(roof), n)
  }
  yardline_100 <- rep_len(yardline_100, n)
  if (anyNA(season)) {
    season[is.na(season)] <- nflreadr::most_recent_season()
  }
  outdoors <- is.na(roof) | roof == "outdoors"
  col <- paste0(
    "era",
    fg_era(season),
    ifelse(outdoors, "_outdoors", "_indoors")
  )
  row <- pmin(pmax(round(yardline_100), 1), 99)
  p <- rep(NA_real_, n)
  ok <- !is.na(row)
  p[ok] <- fg_prob_table[cbind(
    row[ok],
    match(col[ok], colnames(fg_prob_table))
  )]
  p
}
