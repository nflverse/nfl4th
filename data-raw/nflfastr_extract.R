# Copy the parts of nflfastR that nfl4th uses into nfl4th: vegas_wp (regulation), the overtime model and nflfastR's
# field goal table. Writes R/nflfastr_models.R (source, comments kept) and data-raw/nflfastr_models.rds (the model
# objects) in the nfl4th repo given. R_LIBS must load the same nflfastR as the source tree (the functions to copy are
# found from the loaded namespace).
# usage (from the nfl4th repo):
#   Rscript data-raw/nflfastr_extract.R <nflfastR source tree> . "<source label, e.g. nflverse/nflfastR#625 at 856232ab>"
# then rebuild R/sysdata.rda (data-raw/build_sysdata.R) and check that the package's outputs change as expected.
a <- commandArgs(TRUE)
fr <- a[1]
out <- a[2]
src <- a[3]
fs <- asNamespace("nflfastR")
fsn <- ls(fs, all.names = TRUE)
refs <- function(o) {
  if (is.function(o)) {
    unique(c(
      all.names(body(o)),
      unlist(lapply(formals(o), function(f) {
        if (is.language(f)) all.names(f) else character()
      }))
    ))
  } else {
    character()
  }
}
need <- c(
  "calculate_ot_win_probability",
  "wp_ot_start",
  "fg_make_prob"
)
seen <- character()
todo <- need
while (length(todo)) {
  f <- todo[1]
  todo <- todo[-1]
  if (f %in% seen) {
    next
  }
  seen <- c(seen, f)
  todo <- c(todo, setdiff(intersect(refs(get(f, envir = fs)), fsn), seen))
}
data_objs <- c("wp_vegas_model", "ot_wp_dp", "ot_wp_models", "fg_prob_table")
code_objs <- setdiff(seen, data_objs)
cat(
  "objects:",
  length(seen),
  "| data:",
  paste(intersect(seen, data_objs), collapse = ", "),
  "\n"
)
# source of each top-level definition, with the comment block above it
chunks <- list()
found <- character()
for (f in list.files(
  file.path(fr, "R"),
  pattern = "[.]R$",
  full.names = TRUE
)) {
  ex <- parse(f, keep.source = TRUE)
  sr <- attr(ex, "srcref")
  lines <- readLines(f)
  prev_end <- 0L
  for (i in seq_along(ex)) {
    e <- ex[[i]]
    start <- sr[[i]][1]
    end <- sr[[i]][3]
    nm <- if (
      is.call(e) &&
        (identical(e[[1]], as.name("<-")) || identical(e[[1]], as.name("="))) &&
        is.name(e[[2]])
    ) {
      as.character(e[[2]])
    } else {
      NA
    }
    if (!is.na(nm) && nm %in% code_objs) {
      # comments directly above (stop at a blank line before them)
      k <- start - 1L
      while (k > prev_end && grepl("^\\s*#", lines[k])) {
        k <- k - 1L
      }
      chunks[[length(chunks) + 1]] <- c(
        paste0("# ---- from nflfastR ", basename(f)),
        lines[(k + 1L):end],
        ""
      )
      found <- c(found, nm)
    }
    prev_end <- end
  }
}
missing <- setdiff(code_objs, found)
if (length(missing)) {
  stop("not found in nflfastR's R/: ", paste(missing, collapse = ", "))
}
hdr <- c(
  paste0("# Copied from nflfastR (", src, ", MIT license, the same authors):"),
  "# the parts nfl4th uses, so nfl4th doesn't depend on nflfastR.",
  "#   - the overtime model: overtime states, and the tie value of a field goal at",
  "#     the end of regulation (wp_ot_start())",
  "#   - nflfastR's field goal table (fg_make_prob()), which it uses",
  "# nflfastR's regulation model (vegas_wp) isn't needed: nfl4th values",
  "# regulation states with its own model.",
  "# The models (ot_wp_dp, ot_wp_models, fg_prob_table, and wp_kick_start from",
  "# vegas_wp's model) are in R/sysdata.rda, from data-raw/nflfastr_models.rds",
  "# (data-raw/build_sysdata.R).",
  "# Generated by data-raw/nflfastr_extract.R: change it there or in",
  "# nflfastR, not here.",
  ""
)
code <- unlist(chunks)
# Patches, each must apply exactly once. They don't change any value nflfastR returns:
#  - calculate_ot_win_probability(): `wp = TRUE` (nflfastR's behaviour); FALSE skips the pass without the spread,
#    half the work, for callers that only read vegas_wp (nfl4th)
patch <- function(code, old, new) {
  hit <- which(code == old)
  if (length(hit) != 1) {
    stop("patch target found ", length(hit), " times: ", old)
  }
  code[hit] <- new
  code
}
drop_line <- function(code, old) {
  hit <- which(code == old)
  if (length(hit) != 1) {
    stop("line to drop found ", length(hit), " times: ", old)
  }
  code[-hit]
}
code <- patch(
  code,
  "calculate_ot_win_probability <- function(pbp_data, model_data) {",
  "calculate_ot_win_probability <- function(pbp_data, model_data, wp = TRUE) {"
)
code <- patch(
  code,
  "    out$wp[ok] <- ot_wp_states(st[ok, , drop = FALSE], use_spread = FALSE)",
  "    if (wp) out$wp[ok] <- ot_wp_states(st[ok, , drop = FALSE], use_spread = FALSE)"
)
#  - wp_kickoff_start() reads the kickoff spots by rule era from wp_kick_start, the one part of the regulation model
#    (wp_vegas_model$kick_start) the overtime model uses, so the regulation model isn't copied
code <- patch(
  code,
  "wp_kickoff_start <- function(season, model = wp_vegas_model) {",
  "wp_kickoff_start <- function(season, st = wp_kick_start) {"
)
code <- drop_line(code, "  st <- model$kick_start")
hdr <- c(
  hdr[-length(hdr)],
  "# Three changes made by the script, which change no value:",
  "#   - calculate_ot_win_probability(wp = FALSE) skips the pass without the",
  "#     spread, which nfl4th doesn't read",
  "#   - dplyr's if_else(), case_when() and coalesce() are nfl4th's copies",
  "#     (R/vec_helpers.R), so nfl4th doesn't depend on dplyr",
  "#   - wp_kickoff_start() reads the kickoff spots from wp_kick_start instead",
  "#     of the whole regulation model",
  ""
)
#  - dplyr::if_else / case_when / coalesce -> nfl4th's helpers of the same name (R/vec_helpers.R, identical to dplyr
#    1.2's, checked by tests/testthat/test-vec_helpers.R). Any other dplyr call is an error: it needs a helper first.
code <- gsub("dplyr::(if_else|case_when|coalesce)\\(", "\\1(", code)
left <- grep("dplyr::", code, value = TRUE)
if (length(left)) {
  stop(
    "dplyr calls left in the copied code: ",
    paste(trimws(left), collapse = " | ")
  )
}
f <- file.path(out, "R", "nflfastr_models.R")
writeLines(c(hdr, code), f)
# the package is formatted with air (nfl4th's CI checks it)
if (nzchar(Sys.which("air"))) {
  system2("air", c("format", f))
}
# the models, with only the kickoff spots of the regulation model
objs <- mget(data_objs, envir = fs)
objs$wp_kick_start <- objs$wp_vegas_model$kick_start
objs$wp_vegas_model <- NULL
saveRDS(
  objs,
  file.path(out, "data-raw", "nflfastr_models.rds"),
  compress = "xz"
)
cat("wrote", length(found), "definitions,", sum(lengths(chunks)), "lines\n")
